use anyhow::{Context, Result};
use proc_macro2::{Ident, TokenStream};
use quote::quote;
use std::fs;
use chrono::{Local, Datelike}; // Added for signature generation
use sha2::{Digest, Sha256}; // Added for metadata hashing
use serde_json; // For serializing metadata

//use crate::buildrs_ast_utils::ExtractedDecl;
use crate::paths::CratePaths;
use split_decls_types::SplitDeclsConfig;
use crate::ExtractedDecl;
/// Generates the file content for a single declaration and writes it to disk.
pub fn write_declaration_file(
    decl: ExtractedDecl,
    paths: &CratePaths,
    config: &SplitDeclsConfig,
    dry_run: bool,
    _common_uses: &TokenStream, // common_uses is no longer directly injected
    module_name_ident: Ident,
) -> Result<()> {
    let decl_file_path = paths.decls_output_dir.join(format!("{}.rs", module_name_ident.to_string()));
    
    let custom_prelude = if let Some(ref prelude_str) = config.custom_prelude_overlay {
        prelude_str.parse::<TokenStream>().map_err(|e| anyhow::anyhow!("Failed to parse custom prelude overlay: {}", e))?
    } else {
        quote!{}
    };

    // --- Generate Metadata Hash (ZKP Witness Placeholder) ---
    let metadata_json = serde_json::to_string(&decl.metadata)
        .context("Failed to serialize ExtractedDeclMetadata to JSON")?;
    let mut hasher = Sha256::new();
    hasher.update(metadata_json.as_bytes());
    let metadata_hash = format!("{:x}", hasher.finalize());
    // --- End Metadata Hash Generation ---

    // --- Generate Signature Comment ---
    let now = Local::now();
    let generation_date = format!("{}-{:02}-{:02}", now.year(), now.month(), now.day());

    let signature_comment = format!(
        "// This file was generated by split-decls-rs on {}.\n\
         // It contains the '{}' ({}) declaration extracted from {}.\n\
         // Metadata Hash (SHA256): {}\n\
         // Please do not modify this file directly.\n\
         // This hash acts as a ZKP placeholder, summarizing the inputs and AST properties.\n\
         // Future work: Graph matching to LMFDB entries based on this metadata.",
        generation_date, decl.name, decl.kind, paths.crate_name, metadata_hash
    );
    let signature = TokenStream::from_iter(vec![proc_macro2::TokenTree::Group(proc_macro2::Group::new(proc_macro2::Delimiter::None, signature_comment.parse::<TokenStream>().unwrap()))]);
    // --- End Signature Comment Generation ---


    let decl_content_ts = decl.content;
    let file_content = quote! {
        #signature
        use serde::{Deserialize, Serialize};
        use std::collections::HashMap; // Include HashMap for common use in generated types
        #custom_prelude // Include custom prelude if it exists
        #decl_content_ts
    };
    
    if !dry_run {
        fs::write(&decl_file_path, file_content.to_string())
            .context(format!("Failed to write to {}", decl_file_path.display()))?;
        println!("Split '{} {}' to {}", decl.kind, decl.name, decl_file_path.display());
    } else {
        println!(
            "Dry-run: Would split '{} {}' to {}",
            decl.kind,
            decl.name,
            decl_file_path.display()
        );
    }
    Ok(())
}
