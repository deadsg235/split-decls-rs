use anyhow::{Context, Result};
use std::fs;
use std::path::Path;

/// Composes a build.rs file from individual `.rs` files found in an input directory.
/// Each file in the input directory is treated as a module part of the final build.rs.
///
/// This generated build.rs will then include each part as a module and call their
/// respective `run()` functions.
pub fn compose_build_script_from_parts(
    input_dir: &Path,
    output_path: &Path,
) -> Result<()> {
    println!("DBG: Entering compose_build_script_from_parts.");
    println!("DBG: input_dir: {}", input_dir.display());
    println!("DBG: output_path: {}", output_path.display());

    let mut composed_content = String::new();

    composed_content.push_str("// This build.rs file is automatically composed from parts.\n");
    composed_content.push_str("// Do not edit this file directly; edit the source parts instead.\n\n");
    composed_content.push_str("use std::{env, fs, path::Path};\n\n");

    composed_content.push_str("fn main() {\n");
    composed_content.push_str(&format!(
        "    println!(\"cargo:rerun-if-changed={}\");\n",
        input_dir.display()
    ));

    // Collect module paths and their corresponding `run` function calls
    let mut module_calls = Vec::new();

    println!("DBG: Checking if input_dir exists and is a directory.");
    if input_dir.exists() && input_dir.is_dir() {
        println!("DBG: input_dir exists and is a directory. Reading entries.");
        for entry in fs::read_dir(input_dir)? {
            let entry = entry?;
            let path = entry.path();
            println!("DBG: Found entry: {}", path.display());

            if path.extension().and_then(|s| s.to_str()) == Some("rs") {
                let module_name = path
                    .file_stem()
                    .context(format!("Failed to get file stem for {:?}", path))?
                    .to_str()
                    .context(format!("Failed to convert file stem to string for {:?}", path))?;

                composed_content.push_str(&format!(
                    r#"    #[path = "{}/{}.rs"] mod {};"#,
                    input_dir.display(),
                    module_name,
                    module_name
                ));
                composed_content.push_str("\n");

                module_calls.push(format!("{}::run();", module_name));
            }
        }
    } else {
        eprintln!(
            "Warning: Input directory for build script parts not found: {}",
            input_dir.display()
        );
        println!("DBG: Input directory not found or not a directory.");
    }
    composed_content.push_str("\n");

    // Add calls to each module's `run` function
    for call in module_calls {
        composed_content.push_str(&format!("    {}\n", call));
    }

    composed_content.push_str("}\n");

    println!("DBG: Attempting to write generated build.rs to: {}", output_path.display());
    fs::write(output_path, composed_content)?;
    println!("DBG: Successfully wrote generated build.rs.");
    println!("Generated build.rs at: {}", output_path.display());

    Ok(())
}
